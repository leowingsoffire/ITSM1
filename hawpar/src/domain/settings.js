/**
 * Field-level edit policy, keyed by dot-path prefix. The most specific prefix
 * wins. Anything not listed defaults to admin-only (fail closed).
 *
 * Rationale: company identity, branding, SMTP credentials and org-wide
 * document templates are administrative concerns (they affect every user and
 * can carry secrets), while regional *display* preferences are personal
 * enough to leave to any signed-in user.
 */
export const FIELD_POLICY = Object.freeze({
  'company': Role.ADMIN,
  'branding': Role.ADMIN,
  'smtp': Role.ADMIN,
  'templates': Role.ADMIN,
  'regional.autoTimezone': Role.USER,
  'regional.timezone': Role.USER,
  'regional.locale': Role.USER,
  'regional.dateFormat': Role.USER,
  'regional.timeFormat': Role.USER,
  'regional.currency': Role.ADMIN
});

/** @returns {'admin'|'user'} the role required to edit the given dot-path. */
export function policyFor(dotPath) {
  let best = null;
  for (const prefix of Object.keys(FIELD_POLICY)) {
    if (dotPath === prefix || dotPath.startsWith(`${prefix}.`)) {
      if (!best || prefix.length > best.length) best = prefix;
    }
  }
  return FIELD_POLICY[best] ?? Role.ADMIN;
}

