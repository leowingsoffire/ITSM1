/** @returns {string} IANA timezone for the given country, defaulting to Singapore. */
export function timezoneForCountry(country) {
  const key = Object.keys(COUNTRY_TIMEZONES).find(
    (name) => name.toLowerCase() === String(country ?? '').trim().toLowerCase()
  );
  return key ? COUNTRY_TIMEZONES[key] : 'Asia/Singapore';
}

/** @returns {string[]} the full IANA timezone catalogue supported by the Node runtime. */
export function listTimezones() {
  if (typeof Intl.supportedValuesOf === 'function') {
    try {
      return Intl.supportedValuesOf('timeZone');
    } catch {
      /* fall through to the curated list below */
    }
  }
  return Object.values(COUNTRY_TIMEZONES);
}

/** Deep-merges `patch` into `target`, returning a new object. Arrays replace wholesale. */
export function deepMerge(target, patch) {
  if (patch === null || typeof patch !== 'object' || Array.isArray(patch)) return patch;
  const output = { ...target };
  for (const [key, value] of Object.entries(patch)) {
    output[key] = value && typeof value === 'object' && !Array.isArray(value)
      ? deepMerge(target?.[key] ?? {}, value)
      : value;
  }
  return output;
}

/** Flattens a nested object into dot-paths, e.g. `{a:{b:1}}` → `["a.b"]`. */
export function flattenPaths(value, prefix = '') {
  if (value === null || typeof value !== 'object' || Array.isArray(value)) {
    return prefix ? [prefix] : [];
  }
  const paths = [];
  for (const [key, item] of Object.entries(value)) {
    const path = prefix ? `${prefix}.${key}` : key;
    paths.push(...flattenPaths(item, path));
  }
  return paths;
}

/** Removes secrets from a settings document for non-admin/public consumption. */
export function redactSecrets(settings) {
  return {
    ...settings,
    smtp: { ...settings.smtp, password: settings.smtp?.password ? '••••••••' : '' }
  };
}
