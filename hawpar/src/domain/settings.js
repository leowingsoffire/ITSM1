/**
 * Settings domain model: defaults, per-field role policy, and the reference
 * data (timezones, country → timezone mapping) that powers auto-sync.
 *
 * Kept separate from the settings service so the schema/policy can be
 * reviewed and extended without touching persistence or HTTP concerns.
 */

/**
 * The platform has no multi-user identity system (see `public/js/login.js`),
 * so role is a lightweight, client-declared concept carried on the
 * `x-user-role` header. It is enforced here, server-side, so the UI gate can
 * never be the only thing standing between a "user" and an admin-only field —
 * this is still a demo boundary, not real authentication/authorization.
 */
export const Role = Object.freeze({ ADMIN: 'admin', USER: 'user' });
/** The names people see for each role — `user` is presented as "Operator" everywhere. */
export const RoleLabel = Object.freeze({ [Role.ADMIN]: 'Administrator', [Role.USER]: 'Operator' });
export const roleLabel = (role) => RoleLabel[role] ?? String(role);

